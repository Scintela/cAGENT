import assert from 'node:assert/strict';
import {mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import {spawnSync} from 'node:child_process';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const content = path.join(root, 'docs/zh');
const require = createRequire(import.meta.url);
const sidebar = require('../sidebars.js');

function markdownFiles(directory) {
  return readdirSync(directory, {withFileTypes: true}).flatMap(entry => {
    const file = path.join(directory, entry.name);
    return entry.isDirectory() ? markdownFiles(file) : file.endsWith('.md') ? [file] : [];
  });
}
const files = markdownFiles(content);
const ids = new Set(files.map(file => path.relative(content, file).replace(/\.md$/, '')));
const visible = new Set();
function visit(items) {
  for (const item of items) {
    if (typeof item === 'string') visible.add(item);
    else if (item.type === 'doc') visible.add(item.id);
    else if (item.type === 'autogenerated')
      for (const id of ids) {
        if (id.startsWith(item.dirName + '/')) visible.add(id);
      }
    else if (item.items) visit(item.items);
  }
}
visit(sidebar.docs);
for (const id of visible) assert(ids.has(id), 'Unknown sidebar document: ' + id);
for (const id of ids) assert(visible.has(id), 'Document missing from sidebar: ' + id);
for (const file of files) {
  const text = readFileSync(file, 'utf8').replace(/^```[^\n]*\n[\s\S]*?^```\s*$/gm, '');
  for (const match of text.matchAll(/!?\[[^\]]*\]\(([^)]+)\)/g)) {
    const target = match[1].split('#')[0];
    if (!target || /^(https?:|mailto:|\/)/.test(target)) continue;
    const resolved = path.resolve(path.dirname(file), decodeURIComponent(target));
    assert(files.includes(resolved),
      path.relative(root, file) + ': use a valid document or GitHub source link: ' + target);
  }
}
console.log('Validated ' + files.length + ' Chinese documents and sidebar coverage.');

if (process.argv.includes('--examples')) {
  const temporary = mkdtempSync(path.join(tmpdir(), 'cagent-docs-'));
  function run(command, args) {
    const result = spawnSync(command, args, {stdio: 'inherit'});
    if (result.error) throw result.error;
    assert.equal(result.status, 0, command + ' failed');
  }
  try {
    const build = path.join(temporary, 'build');
    run('cmake', ['-S', root, '-B', build, '-DAGENT_BUILD_JSON_CODEC=ON',
      '-DAGENT_BUILD_OPENAI_PROVIDER=ON', '-DAGENT_BUILD_SESSION_RAM=ON',
      '-DAGENT_BUILD_FILE_STORE=ON', '-DAGENT_BUILD_POSIX_FILE_STORE=ON',
      '-DAGENT_BUILD_MARKDOWN_MEMORY=ON', '-DAGENT_BUILD_SESSION_JSONL=ON']);
    run('cmake', ['--build', build]);
    const compiler = process.env.CC || 'cc';
    const includes = ['include', 'providers/model/openai/include',
      'providers/storage/files/include', 'providers/storage/ram/include',
      'providers/storage/jsonl/include', 'providers/memory/markdown/include',
      'ports/posix/storage/include']
      .flatMap(directory => ['-I', path.join(root, directory)]);
    includes.push('-I', path.join(build, 'generated/include'));
    const flags = ['-std=c99', '-Wall', '-Wextra', '-Wpedantic', '-Werror',
      '-DAGENT_BUILD_CONFIG_HEADER="agent_build_config.h"', ...includes];
    let count = 0;
    for (const file of files) {
      const relative = path.relative(content, file);
      if (!/^(getting-started|guides|platforms)\//.test(relative)) continue;
      const text = readFileSync(file, 'utf8');
      for (const match of text.matchAll(/^```c(?: [^\n]*)?\n([\s\S]*?)^```/gm)) {
        const source = path.join(temporary, 'example-' + count++ + '.c');
        writeFileSync(source, match[1]);
        if (relative === 'getting-started/quickstart.md') {
          const executable = path.join(temporary, 'quickstart');
          run(compiler, [...flags, source, path.join(build, 'libcagent_core.a'),
            path.join(build, 'codecs/json/libcagent_json_reader.a'), '-o', executable]);
          const result = spawnSync(executable, [], {encoding: 'utf8'});
          assert.equal(result.status, 0, result.stderr);
          assert.match(result.stdout, /Hello from cAgentV2\./);
          console.log(result.stdout.trim());
        } else {
          run(compiler, [...flags, '-fsyntax-only', source]);
        }
      }
    }
    console.log('Compiled ' + count + ' guide examples; quickstart ran successfully.');
  } finally {
    rmSync(temporary, {recursive: true, force: true});
  }
}
